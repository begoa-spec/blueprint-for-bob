import React, { useState } from 'react';
import { Download, Copy, Check, FileCode, X } from 'lucide-react';
import { StandardRule, RepoConfig } from '../../types';

interface ExportRulesModalProps {
  isOpen: boolean;
  onClose: () => void;
  rules: StandardRule[];
  repoConfig: RepoConfig;
}

export const ExportRulesModal: React.FC<ExportRulesModalProps> = ({
  isOpen,
  onClose,
  rules,
  repoConfig
}) => {
  const [format, setFormat] = useState<'bobrules' | 'markdown' | 'json'>('bobrules');
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const activeRules = rules.filter((r) => r.enabled);

  // Generate file content based on format
  // .bobrules is a plain-text/Markdown file — Bob injects its content
  // verbatim into every conversation. There's no schema, no [sections],
  // no key = "value" syntax; it's just prose Bob reads and follows.
  const generateBobRules = () => {
    const lines = [
      `You are working in the "${repoConfig.repoName}" repository (branch: ${repoConfig.branch}). Follow these ${activeRules.length} standards strictly on every task in this repo.`,
      ``
    ];

    activeRules.forEach((rule, idx) => {
      lines.push(
        `## ${idx + 1}. [${rule.id}] ${rule.title}`,
        `- Severity: ${rule.severity}`,
        `- Category: ${rule.category}`,
        `${rule.bobDirective}`,
        ``
      );
    });

    lines.push(`_Generated by Blueprint for Bob on ${new Date().toISOString()}._`);

    return lines.join('\n');
  };

  const generateMarkdown = () => {
    const lines = [
      `# IBM Bob Coding Agent Instructions`,
      `> Repository: \`${repoConfig.repoName}\` · Branch: \`${repoConfig.branch}\``,
      ``,
      `You are the IBM Bob coding agent. When generating, refactoring, or reviewing code for this repository, you MUST adhere strictly to the following invariants without deviation:`,
      ``
    ];

    activeRules.forEach((rule, idx) => {
      lines.push(
        `### ${idx + 1}. [${rule.id}] ${rule.title} (${rule.severity})`,
        `- **Category**: ${rule.category}`,
        `- **Mandatory Directive**: ${rule.bobDirective}`,
        `- **Context**: ${rule.description}`,
        ``
      );
    });

    lines.push(
      `---`,
      `*Blueprint for Bob - Auto-generated from verified mistake log.*`
    );

    return lines.join('\n');
  };

  const generateJson = () => {
    return JSON.stringify(
      {
        version: '1.0.0',
        generatedAt: new Date().toISOString(),
        repository: repoConfig.repoName,
        branch: repoConfig.branch,
        rules: activeRules.map((r) => ({
          id: r.id,
          title: r.title,
          category: r.category,
          severity: r.severity,
          directive: r.bobDirective,
          description: r.description
        }))
      },
      null,
      2
    );
  };

  const content =
    format === 'bobrules'
      ? generateBobRules()
      : format === 'markdown'
      ? generateMarkdown()
      : generateJson();

  const fileName =
    format === 'bobrules'
      ? '.bobrules'
      : format === 'markdown'
      ? 'bob-instructions.md'
      : 'bob-blueprint.json';

  const handleCopy = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = fileName;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/75 flex items-center justify-center p-4">
      <div className="bg-[#16223b] border border-[#283a62] rounded-lg max-w-3xl w-full p-6 shadow-2xl flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="flex items-start justify-between pb-3 border-b border-[#283a62]">
          <div>
            <h2 className="text-base font-semibold text-white">
              Export IBM Bob Rules File
            </h2>
            <p className="text-xs text-slate-400 mt-0.5">
              Include this file in your repo root or agent prompt so Bob respects your standards.
            </p>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-white p-1"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Format Selector */}
        <div className="flex items-center gap-2 mt-4">
          <span className="text-xs font-semibold text-slate-400">Format:</span>
          <div className="flex items-center gap-1 bg-[#1c2b4a] p-1 rounded border border-[#283a62]">
            <button
              onClick={() => setFormat('bobrules')}
              className={`px-3 py-1 text-xs font-medium rounded transition-colors ${
                format === 'bobrules'
                  ? 'bg-[#213357] text-[#5bc8af]'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              .bobrules (Config)
            </button>
            <button
              onClick={() => setFormat('markdown')}
              className={`px-3 py-1 text-xs font-medium rounded transition-colors ${
                format === 'markdown'
                  ? 'bg-[#213357] text-[#5bc8af]'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              Markdown (Prompt Prefix)
            </button>
            <button
              onClick={() => setFormat('json')}
              className={`px-3 py-1 text-xs font-medium rounded transition-colors ${
                format === 'json'
                  ? 'bg-[#213357] text-[#5bc8af]'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              JSON Blueprint
            </button>
          </div>
        </div>

        {/* Code Content Box */}
        <div className="mt-3 flex-1 overflow-hidden flex flex-col">
          <div className="flex items-center justify-between text-[11px] font-mono text-slate-400 px-3 py-1.5 bg-[#141e33] border border-b-0 border-[#283a62] rounded-t">
            <span>{fileName}</span>
            <span>{activeRules.length} rules active</span>
          </div>
          <pre className="flex-1 p-4 bg-[#0f172a] border border-[#283a62] rounded-b font-mono text-xs text-slate-200 overflow-y-auto whitespace-pre leading-relaxed select-all">
            {content}
          </pre>
        </div>

        {/* Modal Actions */}
        <div className="flex items-center justify-end gap-3 mt-4 pt-3 border-t border-[#283a62]">
          <button
            onClick={handleCopy}
            className="px-4 py-2 text-xs font-medium text-slate-200 bg-[#1c2b4a] hover:bg-[#213357] border border-[#283a62] rounded transition-colors flex items-center gap-1.5"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-[#5bc8af]" />
                <span className="text-[#5bc8af]">Copied to Clipboard</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Content</span>
              </>
            )}
          </button>

          <button
            onClick={handleDownload}
            className="px-4 py-2 text-xs font-semibold text-[#1c2b4a] bg-[#5bc8af] hover:bg-[#4eb39c] rounded transition-colors flex items-center gap-1.5"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download {fileName}</span>
          </button>
        </div>
      </div>
    </div>
  );
};
