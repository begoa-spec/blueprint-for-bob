import { StandardRule, AuditIssue, MistakeLogEntry, RepoConfig, Severity } from '../types';

const SEVERITY_ORDER: Severity[] = ['Critical', 'High', 'Medium', 'Low'];

function groupBySeverity<T extends { severity: Severity }>(items: T[]): Record<Severity, T[]> {
  const grouped: Record<Severity, T[]> = { Critical: [], High: [], Medium: [], Low: [] };
  items.forEach((item) => grouped[item.severity].push(item));
  return grouped;
}

/**
 * Builds a Markdown handover/onboarding document summarizing a repo's
 * standards, current audit findings, and known Bob mistake patterns —
 * meant for a client, a new developer, or your own future reference.
 */
export function generateHandoverDoc(
  repoConfig: RepoConfig,
  rules: StandardRule[],
  issues: AuditIssue[],
  mistakes: MistakeLogEntry[]
): string {
  const activeRules = rules.filter((r) => r.enabled);
  const issuesBySeverity = groupBySeverity(issues);
  const lines: string[] = [];

  lines.push(
    `# Handover Report — ${repoConfig.repoName}`,
    ``,
    `**Branch:** \`${repoConfig.branch}\`  `,
    `**Generated:** ${new Date().toISOString().substring(0, 10)}  `,
    `**Generated by:** Blueprint for Bob`,
    ``,
    `---`,
    ``,
    `## 1. Summary`,
    ``,
    `This document summarizes the current state of the codebase against its enforced coding standards, ` +
      `flags outstanding issues by severity, and lists known mistake patterns previously caught in Bob agent sessions. ` +
      `Use it to get a new developer up to speed quickly, or as a handover artifact for a client.`,
    ``,
    `| Metric | Value |`,
    `|---|---|`,
    `| Active standards enforced | ${activeRules.length} |`,
    `| Open audit issues | ${issues.length} |`,
    `| — Critical | ${issuesBySeverity.Critical.length} |`,
    `| — High | ${issuesBySeverity.High.length} |`,
    `| — Medium | ${issuesBySeverity.Medium.length} |`,
    `| — Low | ${issuesBySeverity.Low.length} |`,
    `| Logged Bob mistakes on file | ${mistakes.length} |`,
    ``,
    `---`,
    ``,
    `## 2. Coding Standards In Effect`,
    ``
  );

  if (activeRules.length === 0) {
    lines.push(`_No standards currently enabled._`, ``);
  } else {
    activeRules.forEach((rule, idx) => {
      lines.push(
        `### 2.${idx + 1} [${rule.id}] ${rule.title} (${rule.severity})`,
        `- **Category:** ${rule.category}`,
        `- **Rule:** ${rule.description}`,
        `- **Enforced as:** ${rule.bobDirective}`,
        ``
      );
    });
  }

  lines.push(`---`, ``, `## 3. Open Audit Issues`, ``);

  if (issues.length === 0) {
    lines.push(`_No open issues from the last audit run._`, ``);
  } else {
    SEVERITY_ORDER.forEach((sev) => {
      const group = issuesBySeverity[sev];
      if (group.length === 0) return;
      lines.push(`### ${sev} (${group.length})`, ``);
      group.forEach((issue) => {
        lines.push(
          `- **\`${issue.fileName}:${issue.line}\`** — ${issue.issue}`,
          `  - Suggested fix: ${issue.suggestion}`
        );
      });
      lines.push(``);
    });
  }

  lines.push(`---`, ``, `## 4. Known Bob Mistake Patterns`, ``);

  if (mistakes.length === 0) {
    lines.push(`_No mistakes logged yet._`, ``);
  } else {
    mistakes.slice(0, 20).forEach((m, idx) => {
      lines.push(
        `### 4.${idx + 1} ${m.title} (${m.severity})`,
        `- **Category:** ${m.category}`,
        `- **Status:** ${m.status}`,
        `- **What went wrong:** ${m.errantBehavior}`,
        `- **Expected instead:** ${m.expectedBehavior}`,
        ``
      );
    });
    if (mistakes.length > 20) {
      lines.push(`_...and ${mistakes.length - 20} more, see the Mistake Log for full history._`, ``);
    }
  }

  lines.push(`---`, ``, `_This report was generated automatically. Review before sharing externally._`);

  return lines.join('\n');
}
